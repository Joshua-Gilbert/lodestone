import struct, sys, gosim
# 1. run LODEBOOT.COM against the image (answer Y)
pc = gosim.PC('test.img', keys=[0x1579])
com = open('src/LODEBOOT.COM', 'rb').read()
pc.mu.mem_write(0x10000, b'\xCD\x20' + b'\0' * 0x7E + b'\x00\x0D')
pc.mu.mem_write(0x10100, com)
for r in (gosim.UC_X86_REG_DS, gosim.UC_X86_REG_ES, gosim.UC_X86_REG_SS): pc.W(r, 0x1000)
pc.W(gosim.UC_X86_REG_SP, 0xFFFE)
pc.run(0x1000, 0x100)
print('LODEBOOT says:\n' + pc.tty)
open('test.img', 'wb').write(pc.img)
img = bytes(pc.img)
print('sector0 OEM', img[3:11], 'BPB kept (spt %d, heads %d, root %d)' % struct.unpack('<HHH', img[0x18:0x1C] + img[0x11:0x13])[0:3:1] if False else '')
# 2. boot it
keys = [0x5000, 0x5000, 0x5000, 0x3B00, 0x011B, 0x5000]
pc = gosim.PC('test.img', keys=keys, mouse_moves=[(30, 40, -20, 0), (32, 20, 10, 0)])
pc.mu.mem_write(0x7C00, img[:512])
pc.W(gosim.UC_X86_REG_DX, 0)
pc.run(0, 0x7C00, slices=600, keys_after=60)
print('TTY:', repr(pc.tty))
print('INT13 reads:', pc.calls13[:12], '... total', len(pc.calls13))
print('mode', hex(pc.mode), 'keys left', len(pc.keys), 'ticks', pc.ticks)
mx = struct.unpack('<HH', bytes(pc.mu.mem_read(0x10000 + 0, 0)) or b'\0\0\0\0')
pc.screen_png('screen.png')
